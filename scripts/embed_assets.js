/**
 * scripts/embed_assets.js
 * Converts all PWA assets in web/ into a self-contained C++ header (src/network/embedded_assets.hpp).
 * This eliminates external file path dependencies, allowing VLive.exe to run stand-alone.
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const webDir = path.join(rootDir, 'web');
const outHeader = path.join(rootDir, 'src', 'network', 'embedded_assets.hpp');

console.log('Packing PWA assets from:', webDir);

function getMimeType(filePath) {
  if (filePath.endsWith('.html') || filePath.endsWith('.htm')) return 'text/html; charset=utf-8';
  if (filePath.endsWith('.css')) return 'text/css; charset=utf-8';
  if (filePath.endsWith('.js')) return 'application/javascript; charset=utf-8';
  if (filePath.endsWith('.json') || filePath.endsWith('.manifest')) return 'application/json';
  if (filePath.endsWith('.svg')) return 'image/svg+xml';
  if (filePath.endsWith('.png')) return 'image/png';
  if (filePath.endsWith('.ico')) return 'image/x-icon';
  if (filePath.endsWith('.otf')) return 'font/otf';
  if (filePath.endsWith('.woff2')) return 'font/woff2';
  return 'application/octet-stream';
}

function getAllFiles(dir, base = '') {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const item of list) {
    const fullPath = path.join(dir, item);
    const relPath = base ? `${base}/${item}` : item;
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(getAllFiles(fullPath, relPath));
    } else {
      results.push({ fullPath, relPath: `/${relPath.replace(/\\/g, '/')}` });
    }
  }
  return results;
}

const files = getAllFiles(webDir);
console.log(`Found ${files.length} assets to embed into executable binary:`);

let header = `// Auto-generated by scripts/embed_assets.js - DO NOT EDIT MANUALLY
#pragma once

#include <string_view>
#include <cstdint>
#include <cstddef>
#include <cstring>

namespace vlive::net {

struct EmbeddedAsset {
    const char* path;
    const char* mime_type;
    const uint8_t* data;
    size_t size;
};

`;

files.forEach((f, idx) => {
  const buf = fs.readFileSync(f.fullPath);
  const varName = `asset_data_${idx}`;
  console.log(` - ${f.relPath} (${buf.length} bytes)`);

  header += `// Asset: ${f.relPath}\n`;
  header += `static const uint8_t ${varName}[${buf.length}] = {\n`;
  
  // Format bytes in rows of 16 for clean compilation
  for (let i = 0; i < buf.length; i += 16) {
    const chunk = buf.slice(i, Math.min(i + 16, buf.length));
    header += '    ' + Array.from(chunk).map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',\n';
  }
  header += `};\n\n`;
});

header += `static const EmbeddedAsset g_embedded_assets[] = {\n`;
files.forEach((f, idx) => {
  const mime = getMimeType(f.relPath);
  const buf = fs.readFileSync(f.fullPath);
  header += `    { "${f.relPath}", "${mime}", asset_data_${idx}, ${buf.length} },\n`;
});
header += `};\n\n`;

header += `inline const EmbeddedAsset* findEmbeddedAsset(std::string_view reqPath) {
    std::string_view path = reqPath;
    if (path.empty() || path == "/") {
        path = "/index.html";
    }
    // Strip query string if present
    size_t q = path.find('?');
    if (q != std::string_view::npos) {
        path = path.substr(0, q);
    }
    for (const auto& item : g_embedded_assets) {
        if (item.path == path) {
            return &item;
        }
    }
    return nullptr;
}

} // namespace vlive::net
`;

fs.writeFileSync(outHeader, header);
console.log('[SUCCESS] Generated embedded assets header:', outHeader);
